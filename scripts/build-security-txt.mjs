/**
 * Generate public/.well-known/security.txt.
 *
 * RFC 9116 makes `Expires` mandatory and treats an expired file as invalid, so
 * a hand-written date is a slow leak: it is correct the day it is typed and
 * silently wrong a year later. `pnpm build` runs this first, which means every
 * deploy ships a file that expires a year from that deploy rather than a year
 * from whenever somebody last remembered.
 *
 * Writes into public/ rather than straight into dist/ so the dev server, the
 * committed copy and the deployed copy all say the same thing. The file is
 * generated but committed, like the fonts and the OG cards.
 *
 * Contact and origin come from src/siteMeta.js — plain ESM with no JSX, so node
 * loads it as-is (same trick as scripts/socialHead.mjs).
 *
 * Run directly to refresh the committed copy:  pnpm build:security
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { SITE_ORIGIN, SECURITY_CONTACT, LANGUAGE, REPO_URL } from "../src/siteMeta.js";

const OUT = "public/.well-known/security.txt";

/**
 * Under a year, per RFC 9116 section 2.5.5. Not exactly a year: a file
 * generated on the 29th of February would otherwise land on an invalid date.
 */
const VALID_DAYS = 365;

/** Pure so src/test/staticFiles.test.js can pin the format without writing a file. */
export function securityTxt(now = new Date()) {
  const expires = new Date(now.getTime() + VALID_DAYS * 24 * 60 * 60 * 1000);
  // End of that UTC day — the exact second is noise, and a round one is easier
  // to eyeball against the deploy date.
  expires.setUTCHours(23, 59, 59, 0);

  return `# Security policy for ${SITE_ORIGIN.replace(/^https:\/\//, "")}
# https://www.rfc-editor.org/rfc/rfc9116
#
# Generated by scripts/build-security-txt.mjs — do not edit by hand.
# Expires is set ${VALID_DAYS} days from the build that produced this file.

Contact: mailto:${SECURITY_CONTACT}
Expires: ${expires.toISOString().replace(/\.\d{3}Z$/, ".000Z")}
Preferred-Languages: ${LANGUAGE.split("-")[0]}
Canonical: ${SITE_ORIGIN}/.well-known/security.txt
Policy: ${REPO_URL}/blob/main/SECURITY.md
`;
}

// Only when run as a script — importing this from a test must not write files.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = fileURLToPath(new URL(`../${OUT}`, import.meta.url));
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, securityTxt());
  console.log(`security.txt -> ${OUT}`);
}
